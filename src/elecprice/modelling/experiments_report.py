"""``reports/experiments.md`` from ``reports/experiments.json``."""

from __future__ import annotations

from pathlib import Path


def _gbp(x: float) -> str:
    return f"£{x:.3f}"


def _row(r: dict) -> str:
    if r["name"] == "baseline":
        return (
            f"| **current model** | | {r['pinball_mean']:.3f} | | | | "
            f"{r['coverage']:.1%} | £{r['mae_p50']:.2f} | |"
        )
    lo, hi = r["gain_interval"]
    return (
        f"| `{r['name']}` | {r['pattern'].split('.')[0]} | {r['pinball_mean']:.3f} "
        f"| {r['relative_gain']:+.1%} | {_gbp(lo)} to {_gbp(hi)} "
        f"| {r['folds_better']} of {r['folds']} | {r['coverage']:.1%} | £{r['mae_p50']:.2f} "
        f"| {'**yes**' if r['adopted'] else 'no'} |"
    )


def markdown(res: dict) -> str:
    rule = res["rule"]
    base = next(r for r in res["experiments"] if r["name"] == "baseline")
    others = [r for r in res["experiments"] if r["name"] != "baseline"]
    lines = [
        "# Experiments",
        "",
        f"_Generated by `elec experiments`. Selection folds {res['folds'][0]} to "
        f"{res['folds'][-1]} ({len(res['folds'])} monthly walk-forward folds, "
        f"{base['n']:,} half-hours, delivery days up to {res['last_day']}). The hold-out "
        f"(from {res['holdout_from']}) is not read._",
        "",
        "Each experiment is one change to the current model, motivated by a pattern in "
        "[data_patterns.md](data_patterns.md). The rule for adopting a change was fixed in "
        "DECISIONS.md before the first run:",
        "",
        f"1. the 95% moving-block bootstrap interval ({rule['block_days']}-day blocks, "
        f"{rule['bootstrap']:,} resamples) of the mean daily reduction in pinball loss lies "
        "above zero;",
        f"2. pinball loss is lower in at least {rule['min_folds_better']} of the "
        f"{len(res['folds'])} folds;",
        f"3. pooled P10-P90 coverage stays between {rule['coverage_range'][0]:.0%} and "
        f"{rule['coverage_range'][1]:.0%}.",
        "",
        "Pinball loss is in £/MWh, averaged over P10, P50 and P90; lower is better. The "
        "interval is for the mean daily reduction against the current model (positive means "
        "the change helps).",
        "",
        "| Experiment | Pattern | Pinball | Change in pinball | 95% interval of the daily "
        "gain | Folds better | Coverage | MAE P50 | Adopted |",
        "|---|---|---|---|---|---|---|---|---|",
        _row(base),
        *[_row(r) for r in others],
        "",
        "## What each experiment changed and what it showed",
        "",
    ]
    for r in others:
        lo, hi = r["gain_interval"]
        verdict = (
            "passes the rule"
            if r["adopted"]
            else "fails the rule: "
            + "; ".join(
                reason
                for ok, reason in (
                    (lo > 0, "the interval includes zero or lies below it"),
                    (
                        r["folds_better"] >= rule["min_folds_better"],
                        f"better in only {r['folds_better']} of {r['folds']} folds",
                    ),
                    (
                        rule["coverage_range"][0] <= r["coverage"] <= rule["coverage_range"][1],
                        f"coverage {r['coverage']:.1%} is out of range",
                    ),
                )
                if not ok
            )
        )
        lines += [
            f"**`{r['name']}`** (pattern {r['pattern']}): {r['change']}. Pinball "
            f"{r['pinball_mean']:.3f} against {base['pinball_mean']:.3f} "
            f"({r['relative_gain']:+.1%}; daily gain {_gbp(lo)} to {_gbp(hi)}), better in "
            f"{r['folds_better']} of {r['folds']} folds, coverage {r['coverage']:.1%}. "
            f"It {verdict}.",
            "",
        ]
    combo = res.get("combination")
    lines += ["## Adopted", ""]
    if not res["adopted"]:
        lines += [
            "Nothing passes the rule, so the current model stays as it is. The table is the "
            "evidence for its design: each alternative the data suggested was tried and did "
            "not beat it reliably.",
            "",
        ]
    elif combo:
        lo, hi = combo["gain_interval"]
        lines += [
            "Passing on their own: " + ", ".join(f"`{m}`" for m in combo["members"]) + ". "
            f"Together: pinball {combo['pinball_mean']:.3f} ({combo['relative_gain']:+.1%}, "
            f"daily gain {_gbp(lo)} to {_gbp(hi)}), better in {combo['folds_better']} of "
            f"{combo['folds']} folds, coverage {combo['coverage']:.1%}: the combination "
            + ("passes the rule and is adopted." if combo["adopted"] else "fails the rule.")
            + "",
            "",
        ]
    else:
        lines += [f"Adopted: `{res['adopted'][0]}`.", ""]
    if res.get("holdout"):
        lines += holdout_lines(res["holdout"])
    return "\n".join(lines)


def holdout_lines(h: dict) -> list[str]:
    lo, hi = h["gain_interval"]
    return [
        "## The hold-out, read once",
        "",
        f"The adopted configuration against the current model on folds {h['folds'][0]} to "
        f"{h['folds'][-1]} ({h['n']:,} half-hours), which no choice above has seen:",
        "",
        "| Model | Pinball | MAE P50 | Coverage |",
        "|---|---|---|---|",
        f"| current | {h['base']['pinball_mean']:.3f} | £{h['base']['mae_p50']:.2f} "
        f"| {h['base']['coverage']:.1%} |",
        f"| adopted | {h['new']['pinball_mean']:.3f} | £{h['new']['mae_p50']:.2f} "
        f"| {h['new']['coverage']:.1%} |",
        "",
        f"Change in pinball {h['relative_gain']:+.1%} (95% interval of the daily gain "
        f"{_gbp(lo)} to {_gbp(hi)}), better in {h['folds_better']} of {h['folds_n']} folds.",
        "",
    ]


def write(res: dict, out_dir: Path) -> None:
    (out_dir / "experiments.md").write_text(markdown(res))
